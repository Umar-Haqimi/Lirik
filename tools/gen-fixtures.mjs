#!/usr/bin/env node
// Bundle tests/fixtures/* into tests/fixtures/fixtures.gen.mjs so the shared test tables can read
// fixtures in V4 too (QML's JS has no file access).
//   node tools/gen-fixtures.mjs          regenerate
//   node tools/gen-fixtures.mjs --check  exit 1 if the bundle is stale (used by tools/dev.sh)

import fs from "node:fs"
import path from "node:path"

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..")
const DIR = path.join(ROOT, "tests/fixtures")
const OUT = path.join(DIR, "fixtures.gen.mjs")
const SUBDIRS = ["lrc", "lyricsfile", "ttml", "malformed-ttml", "qrc", "api", "tracks"]

function build() {
    const entries = []
    for (const sub of SUBDIRS) {
        const d = path.join(DIR, sub)
        if (!fs.existsSync(d)) continue
        for (const f of fs.readdirSync(d).sort()) {
            const p = path.join(d, f)
            if (!fs.statSync(p).isFile()) continue
            entries.push([`${sub}/${f}`, fs.readFileSync(p, "utf8")])
        }
    }
    let src = "// GENERATED by tools/gen-fixtures.mjs — do not edit. Synthetic fixtures only.\n"
    src += "export const FIXTURES = {\n"
    for (const [k, v] of entries) src += `    ${JSON.stringify(k)}: ${JSON.stringify(v)},\n`
    src += "}\n\nexport function fixture(name) {\n"
    src += "    if (!Object.prototype.hasOwnProperty.call(FIXTURES, name)) throw new Error(\"no fixture \" + name)\n"
    src += "    return FIXTURES[name]\n}\n\n"
    src += "export function fixtureNames(prefix) {\n"
    src += "    return Object.keys(FIXTURES).filter(function (k) { return k.indexOf(prefix) === 0 })\n}\n"
    return src
}

const src = build()
if (process.argv.includes("--check")) {
    const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : ""
    if (cur !== src) {
        console.error("fixtures.gen.mjs is stale")
        process.exit(1)
    }
} else {
    fs.writeFileSync(OUT, src)
    console.log(`wrote ${path.relative(ROOT, OUT)}`)
}
